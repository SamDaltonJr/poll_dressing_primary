export const TEXAS_COUNTY_NAMES: string[] = TEXAS_COUNTIES.map((c) => c.name);

const byName = new Map(TEXAS_COUNTIES.map((c) => [c.name.toLowerCase(), c]));

/** "Fort Bend" → "fort-bend". Stable slug used in Firestore doc IDs and location IDs. */
export function countySlug(county: string): string {
  return county.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

/** Case-insensitive lookup; tolerates a trailing "County". */
export function findCounty(name: string | null | undefined): TexasCounty | null {
  if (!name) return null;
  return byName.get(name.trim().replace(/\s+county$/i, '').toLowerCase()) ?? null;
}
